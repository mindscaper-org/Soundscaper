import assert from 'node:assert/strict';
import test from 'node:test';
import { createSoundscaperProjectRuntimeSelection } from '../src/soundscaper/editor-project-runtime-selection.ts';
import { createSoundscaperScapeNativeRuntime } from '../src/soundscaper/editor-scape-native.ts';
import { validateSoundscaperProject } from '../src/soundscaper/editor-project-validation.ts';
import { exportScapeProject } from '../src/common/editor/scape-project.js';
import { effectAutomationProject } from './helpers/next-time-preserving-effect-project.ts';
import { createMemoryFfmpeg } from './helpers/audio-editor-controller-fixtures.js';
import { COPY, createAudioEditorController, createMemoryEngine, createProjectStore } from './helpers/audio-editor-controller-harness.js';
type Options = NonNullable<Parameters<typeof createAudioEditorController>[1]>;
for (const asNewClip of [false, true]) test(`NP046: ${asNewClip ? 'separate' : 'joined'} Paste Insert preserves native automation geometry`, async context => {
 const {project,source,samples}=effectAutomationProject();
 const runtime=createSoundscaperProjectRuntimeSelection(); const store=createProjectStore({indexedDB:null,preferOpfs:false,databaseName:context.name});
 const writer=await store.beginSourceWrite(source.storageKey,source);await writer.write([samples]);await writer.commit();
 const controller=createAudioEditorController(null,{headless:true,locale:'en',copy:COPY,projectRuntime:runtime,sessionController:runtime.createSessionController(),store,scapeProjectRuntime:createSoundscaperScapeNativeRuntime(),engine:createMemoryEngine() as unknown as Options['engine'],ffmpeg:createMemoryFfmpeg() as unknown as Options['ffmpeg']});
 context.after(async()=>{await controller.dispose();});await controller.ready;
 const archive=await exportScapeProject(project,store);assert.ok(archive.blob instanceof Blob);
 await controller.actions.project.openScapeFile(new File([archive.blob],'Automation.sscape'),()=> 'copy');
 await controller.actions.preferences.update({editing:{alwaysPasteAsNewClip:asNewClip}});
 controller.actions.timeline.setExactSelection(0,12000,{trackIds:['voice']});controller.actions.edit.copy();
 controller.actions.timeline.setExactSelection(24000,24000,{trackIds:['voice']});controller.actions.transport.seek(24000);
 const before: unknown = controller.project; assert.ok(validateSoundscaperProject(before));
 await controller.actions.edit.pasteInsert();
 const after:unknown=controller.project;assert.ok(validateSoundscaperProject(after));
 assert.equal(after.clips.length,asNewClip ? 3 : 1);assert.equal(after.automationLanes[0]?.points.find(point=>point.id==='rise')?.position,12000);
 assert.equal(after.automationLanes[0]?.points.find(point=>point.id==='end')?.position,60000);
 assert.equal(after.automationLanes[0]?.points.find(point=>point.id==='fall')?.position,36000);
 controller.actions.edit.undo(); assert.deepEqual(controller.project?.automationLanes,before.automationLanes);
 controller.actions.edit.redo(); assert.deepEqual(controller.project?.automationLanes,after.automationLanes);
});
