import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { MANAGED_FEATURES } from '../desktop/managed-policy.ts';

const descriptions = {
	OnlineFeaturesAllowed: ['Allow online features', 'Disabling this policy prohibits application internet features, including updates, downloads, online providers, Web VCR and external links. Local automation has its own policy.'],
	ApplicationUpdatesAllowed: ['Allow application updates', 'Disabling this policy prohibits automatic and manual update checks, downloads and pending installations. MSI installations always use administrator-managed updates.'],
	ModelDownloadsAllowed: ['Allow model and runtime downloads', 'Disabling this policy prohibits downloads of local-assistance models and runtimes. Installed models and offline preseeded installation remain available.'],
	FreesoundAllowed: ['Allow Freesound', 'Disabling this policy prohibits Freesound authorization, requests, previews, downloads and uploads.'],
	AudiocomAllowed: ['Allow audio.com', 'Disabling this policy prohibits audio.com authorization, requests, previews, downloads, uploads and project synchronization.'],
	WebVcrAllowed: ['Allow Web VCR', 'Disabling this policy prohibits the Framescaper Web VCR guest browser. It has no effect in Soundscaper.'],
	ExternalLinksAllowed: ['Allow external links', 'Disabling this policy prohibits links and authorization handoffs to the system browser.'],
	ExternalCodecInstallationAllowed: ['Allow external codec installation', 'Disabling this policy prohibits in-app package-manager installation of FFmpeg. Existing local codecs remain available.'],
	LocalIntegrationsAllowed: ['Allow local networking integrations', 'Disabling this policy prohibits starting the local MCP server and live Blender connections. File-based Blender export remains available.'],
};
const output = new URL('../desktop/policies/', import.meta.url);
const check = process.argv.includes('--check');
for (const productId of ['soundscaper', 'framescaper']) {
	const product = productId === 'soundscaper' ? 'Soundscaper' : 'Framescaper';
	const namespace = `Mindscaper.${product}`;
	const key = `Software\\Policies\\Mindscaper\\${product}`;
	const policies = MANAGED_FEATURES.map(feature => `    <policy name="${feature}" class="Both" displayName="$(string.${feature})" explainText="$(string.${feature}Help)" key="${key}" valueName="${feature}">
      <parentCategory ref="Application"/><supportedOn ref="windows:SUPPORTED_Windows10"/>
      <enabledValue><decimal value="1"/></enabledValue><disabledValue><decimal value="0"/></disabledValue>
    </policy>`).join('\n');
	const admx = `<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: AGPL-3.0-only; generated by scripts/generate-windows-policy-templates.mjs -->
<policyDefinitions xmlns="http://www.microsoft.com/GroupPolicy/PolicyDefinitions" revision="1.0" schemaVersion="1.0">
  <policyNamespaces><target prefix="${productId}" namespace="${namespace}"/><using prefix="windows" namespace="Microsoft.Policies.Windows"/></policyNamespaces>
  <resources minRequiredRevision="1.0"/>
  <categories><category name="Application" displayName="$(string.Application)"/></categories>
  <policies>
${policies}
    <policy name="LaunchPreferences" class="Both" displayName="$(string.LaunchPreferences)" explainText="$(string.LaunchPreferencesHelp)" presentation="$(presentation.LaunchPreferences)" key="${key}">
      <parentCategory ref="Application"/><supportedOn ref="windows:SUPPORTED_Windows10"/>
      <elements><text id="LaunchPreferences" valueName="LaunchPreferences" required="true" maxLength="65536"/></elements>
    </policy>
  </policies>
</policyDefinitions>
`;
	const strings = MANAGED_FEATURES.map(feature => `      <string id="${feature}">${descriptions[feature][0]}</string>
      <string id="${feature}Help">${descriptions[feature][1]} Settings are read at application startup. Machine policy takes precedence over user policy. Allowing a feature does not replace user consent.</string>`).join('\n');
	const adml = `<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: AGPL-3.0-only; generated by scripts/generate-windows-policy-templates.mjs -->
<policyDefinitionResources xmlns="http://www.microsoft.com/GroupPolicy/PolicyDefinitions" revision="1.0" schemaVersion="1.0">
  <displayName>${product} policies</displayName><description>Administrator policies for ${product}</description>
  <resources>
    <stringTable>
      <string id="Application">${product}</string>
${strings}
      <string id="LaunchPreferences">Reset selected preferences on launch</string>
      <string id="LaunchPreferencesHelp">Apply a versioned JSON preference patch on each application launch. Example: {&quot;schemaVersion&quot;:1,&quot;desktop&quot;:{&quot;updatesEnabled&quot;:false},&quot;editor&quot;:{&quot;appearance&quot;:{&quot;theme&quot;:&quot;dark&quot;}}}. Unspecified settings remain unchanged. Users may change these preferences during the session. On the next launch the patch is reapplied. Machine fields take precedence over user fields. Removing this policy stops resetting values; it does not restore old preferences.</string>
    </stringTable>
    <presentationTable><presentation id="LaunchPreferences"><textBox refId="LaunchPreferences"><label>Preference patch (JSON)</label></textBox></presentation></presentationTable>
  </resources>
</policyDefinitionResources>
`;
	for (const [name, content] of [[`${productId}.admx`, admx], [join('en-US', `${productId}.adml`), adml]]) {
		const path = new URL(name, output);
		if (check) {
			if (await readFile(path, 'utf8') !== content) throw new Error(`Regenerate Windows policy templates: ${name}`);
		} else {
			await mkdir(new URL('.', path), { recursive: true });
			await writeFile(path, content);
		}
	}
}
